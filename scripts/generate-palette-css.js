import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { STORAGE_KEYS } from "../src/config/storage.js";
import { DARK_PALETTE, LIGHT_PALETTE } from "../src/theme/palette.js";
import { PALETTE_TOKEN_MAP } from "../src/theme/paletteTokens.js";
import {
	DARK_MEDIA_QUERY,
	DEFAULT_THEME_MODE,
} from "../src/theme/themeConfig.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");

const declarations = Object.entries(PALETTE_TOKEN_MAP).map(
	([key, token]) =>
		`\t${token}: light-dark(${LIGHT_PALETTE[key]}, ${DARK_PALETTE[key]});`,
);

const paletteOutput = path.resolve(root, "src/theme/palette.generated.css");
await writeFile(
	paletteOutput,
	`/* Generated by scripts/generate-palette-css.js — do not edit. */\n:root {\n${declarations.join("\n")}\n}\n`,
);

const q = JSON.stringify;
const bootstrap = `/* Generated by scripts/generate-palette-css.js — do not edit. */
(() => {
  let mode = ${q(DEFAULT_THEME_MODE)};
  let highContrast = null;
  try {
    mode = localStorage.getItem(${q(STORAGE_KEYS.themeMode)}) || ${q(DEFAULT_THEME_MODE)};
    highContrast = localStorage.getItem(${q(STORAGE_KEYS.highContrast)});
    const isDark = mode === 'dark' || (mode === 'system' && window.matchMedia(${q(DARK_MEDIA_QUERY)}).matches);
    document.documentElement.setAttribute('data-theme', isDark ? 'dark' : 'light');
    if (highContrast === 'true') {
      document.documentElement.setAttribute('data-high-contrast', 'true');
    }
    const metaTheme = document.querySelector('meta[name="theme-color"]');
    if (metaTheme) {
      metaTheme.setAttribute('content', isDark ? ${q(DARK_PALETTE.backgroundBody)} : ${q(LIGHT_PALETTE.backgroundBody)});
    }
  } catch (_error) {}
})();
`;

const bootstrapOutput = path.resolve(root, "public/theme-bootstrap.js");
await writeFile(bootstrapOutput, bootstrap);

console.log(
	`Generated ${path.relative(process.cwd(), paletteOutput)} and ${path.relative(process.cwd(), bootstrapOutput)}`,
);
