import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { DARK_PALETTE, LIGHT_PALETTE } from "../src/theme/palette.js";
import { PALETTE_TOKEN_MAP } from "../src/theme/paletteTokens.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const output = path.resolve(here, "../src/theme/palette.generated.css");

const declarations = Object.entries(PALETTE_TOKEN_MAP).map(
	([key, token]) =>
		`\t${token}: light-dark(${LIGHT_PALETTE[key]}, ${DARK_PALETTE[key]});`,
);

await writeFile(
	output,
	`/* Generated by scripts/generate-palette-css.js — do not edit. */\n:root {\n${declarations.join("\n")}\n}\n`,
);

console.log(`Generated ${path.relative(process.cwd(), output)}`);
